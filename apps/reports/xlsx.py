"""The Excel export, laid out like the client's sample workbook:

    row 1  the report's title (merged, bold)
    row 2  From : ... To : ...  and the filters applied
    row 3  Report Generated On : ...   Report Generated By : ...
    row 4  the column headers, the client's own names
    then   the rows; a block report repeats the headers before each block
           (as the sample does per state) and closes it with its TOTAL row;
           the GRAND TOTAL last.

An order with several vehicles (Rent Details) writes its order columns once,
merged down its vehicle rows. Money is a real number at 3 decimals, times are
real Excel date-times -- so the sheet can be summed and sorted.
"""

import io

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from apps.reports.base import COUNT, DATA, DATE, DATETIME, MONEY, PERCENT

FORMATS = {MONEY: "#,##0.000", COUNT: "#,##0", PERCENT: "0.00", DATETIME: "dd/mm/yyyy hh:mm:ss AM/PM",
           DATE: "dd/mm/yyyy"}
BOLD = Font(bold=True)
HEAD_FILL = PatternFill("solid", fgColor="F2F2F2")
THIN = Side(style="thin", color="D9D9D9")
GRID = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
TOP = Alignment(vertical="top")
WRAP = Alignment(wrap_text=True, vertical="center", horizontal="center")


def workbook(report, result, lines):
    """The export as bytes. `lines` are the three header lines (title, filters,
    generated on/by)."""
    wb = Workbook()
    ws = wb.active
    ws.title = report.sheet_title[:31]
    columns = result.columns
    width = len(columns)

    for r, (text, size) in enumerate(zip(lines, (14, 11, 11), strict=False), start=1):
        ws.cell(row=r, column=1, value=text).font = Font(bold=True, size=size)
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=width)
    row = 4
    _header(ws, row, columns)
    ws.freeze_panes = ws.cell(row=row + 1, column=1)
    row += 1

    previous = DATA
    for item in result.rows:
        if result.blocks and item.kind == DATA and previous != DATA and row > 5:
            row += 1                                     # a blank line, then the headers again
            _header(ws, row, columns)
            row += 1
        row = _write(ws, row, item, columns)
        previous = item.kind

    for c, column in enumerate(columns, start=1):
        ws.column_dimensions[get_column_letter(c)].width = column.width
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


def _header(ws, row, columns):
    for c, column in enumerate(columns, start=1):
        cell = ws.cell(row=row, column=c, value=column.label)
        cell.font, cell.fill, cell.border, cell.alignment = BOLD, HEAD_FILL, GRID, WRAP
    ws.row_dimensions[row].height = 30


def _write(ws, row, item, columns):
    """One table row -- or, for an order with vehicle lines, its block of rows.
    Returns the next free row."""
    total = item.kind != DATA
    span = max(len(item.lines or []), 1)
    for c, column in enumerate(columns, start=1):
        if column.part == "line":
            for i in range(span):
                value = (item.lines[i].get(column.key) if item.lines else item.cells.get(column.key))
                _cell(ws, row + i, c, value, column, total)
            continue
        value = item.cells.get(column.key)
        if total and c == 1:
            value = item.label
        _cell(ws, row, c, value, column, total)
        if span > 1:
            ws.merge_cells(start_row=row, start_column=c, end_row=row + span - 1, end_column=c)
            ws.cell(row=row, column=c).alignment = TOP
            for i in range(1, span):
                ws.cell(row=row + i, column=c).border = GRID
    return row + span


def _cell(ws, row, col, value, column, bold):
    cell = ws.cell(row=row, column=col, value=value)
    cell.border = GRID
    if column.kind in FORMATS and value is not None and not isinstance(value, str):
        cell.number_format = FORMATS[column.kind]
    if bold:
        cell.font = BOLD
